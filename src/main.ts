async function onSetupSave(event: any, form) {
  event.preventDefault();
  const payload = formJson(form);
  state.setupSaving = true;
  state.setupMessage = setupT('savingSetup');
  updateSetupMessage();
  form.querySelectorAll('input, select, button').forEach((control) => {
    control.disabled = true;
  });
  try {
    const response = await fetch('/api/setup/save', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload),
    });
    const result = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(result.message || 'Setup failed.');
    state.setupStatus = result;
    state.setupMessage = setupT('setupSaved');
    await refreshPublicPhotos();
    setMode(VIEW.studio);
    ensureAdminLoaded();
  } catch (error: any) {
    state.setupMessage = setupErrorMessage(error.message);
    updateSetupMessage();
  } finally {
    state.setupSaving = false;
    form.querySelectorAll('input, select, button').forEach((control) => {
      control.disabled = false;
    });
  }
}

